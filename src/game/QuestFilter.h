	inline bool IsPerGame(std::uint8_t a_file, std::uint32_t a_quest)
	{
		return std::ranges::binary_search(PER_GAME, std::pair{ a_file, a_quest }, {}, [](const Local& a_local) { return std::pair{ a_local.file, a_local.quest }; });
	}

