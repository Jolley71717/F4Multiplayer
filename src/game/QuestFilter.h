// Which of the game's quests a session shares, by what the game's files say about each one: the type it
// is filed under, whether it has objectives, and the name its designers gave it. Kept free of the game so
// it can be tested; QuestSync reads these off TESQuest.
namespace QuestFilter
{
	// A quest as the filter sees it.
	struct Quest
	{
		std::uint32_t    formId = 0;
		std::int8_t      type = 0;               // QUEST_DATA::questType
		bool             hasObjectives = false;  // it has objectives at all, shown or not
		std::string_view editorId;               // the designers' name for it (TESQuest::formEditorID)
	};

	// QUEST_DATA::questType values that are shared: main quest, the four factions, side quests
	// and DLC quests. 0 is "none" (internal quests) and 6 is "miscellaneous" (radiant/ambient).
	inline bool IsSharedType(std::int8_t a_type)
	{
		return a_type > 0 && a_type != 6;
	}

	// The factions' last quests, which the game files under no type (0, like its internal quests). They
	// are shared with the rest of the story when the host shares it; their stages award achievements.
	// Fallout4.esm: Inst305 "Powering Up", BoS302 "Blind Betrayal", BoS304 "Ad Victoriam".
	inline constexpr std::array<std::uint32_t, 3> STORY_FINALES{ 0x000A274B, 0x000B9F9D, 0x00173ED9 };

	inline bool IsFinale(const Quest& a_quest)
	{
		return a_quest.type == 0 && std::ranges::find(STORY_FINALES, a_quest.formId) != STORY_FINALES.end();
	}

	// Whether this is a name the game gives its dialogue quests: Dialogue<Place> (DialogueDiamondCity,
	// DialogueGoodneighbor, DialogueDiamondCityEntrance), after the add-on's prefix in an add-on's files
	// (DLC03DialogueFarHarbor, DLC04_DialogueNukaTown).
	inline bool IsDialogueName(std::string_view a_editorId)
	{
		if (a_editorId.starts_with("DLC")) {
			auto        rest = a_editorId.substr(3);
			std::size_t digits = 0;
			while (digits < rest.size() && std::isdigit(static_cast<unsigned char>(rest[digits]))) {
				++digits;
			}
			if (digits > 0) {
				rest.remove_prefix(digits);
				if (rest.starts_with("_")) {
					rest.remove_prefix(1);
				}
				a_editorId = rest;
			}
		}
		return a_editorId.starts_with("Dialogue");
	}

	// A dialogue quest: what a place's people say and the scenes they play, which the game files under no
	// type (0) with no objectives (nothing of it is ever in the Pip-Boy), and names Dialogue<Place>. Some
	// of their stages change the world on the story's way: Diamond City's entrance scene (Piper and Danny
	// Sullivan at the intercom, DialogueDiamondCityEntrance) opens the city's gate at its 32, and without
	// it a friend's gate stays shut where the host's opened. So they are shared with the rest of the story
	// when the host shares it. With no objective ever shown, such a quest counts as started once it is
	// running or has stages done, its stages aren't steps in order (only one done here is past), and once
	// it ran and stopped it is over (see QuestSync). The game's other quests under no type stay its own:
	// its random encounters, companions' talks, tutorials and dungeons are each game's, or run in the
	// background with nothing to show for them.
	inline bool IsDialogue(const Quest& a_quest)
	{
		return a_quest.type == 0 && !a_quest.hasObjectives && IsDialogueName(a_quest.editorId);
	}

	// A quest by the file it comes from (StageRules::File: 0 Fallout4.esm, 1 DLCCoast.esm, 2 DLCRobot.esm, 3
	// DLCNukaWorld.esm) and its form ID there, load index masked off (an add-on's is the player's load order's).
	struct Local
	{
		std::uint8_t  file;
		std::uint32_t quest;
	};

	// Side quests the game files under a shared type that each game fills its own way, as a radiant: the story manager
	// starts them (the quest's own event, ENAM, or a story manager quest node) and at least one of their aliases is
	// filled by its conditions or from that event: the settlement that asks, the place to clear, the caches, the rival
	// boss. Each game picks its own, so a friend's stage of one means nothing here, and set here it started the quest with
	// this game's own targets (up to 0.11.0). So they are never shared: each player's own, as the radiants that
	// src/game/RadiantRules.h leaves alone (it decides the radiants it lists, Fallout4.esm's). Generated by
	// tools/questscan.ps1 -PerGame from the game's files: the shared-type quests with objectives the story manager starts
	// with such aliases, but RadiantRules.h's (29). Sorted by file and form ID.
	// RadiantSync could share some of them by their run, as the Minutemen's settlement requests: by their aliases, those
	// filled with the game's own references and locations only (no actor made at runtime): DN121 and DN151 (Saugus
	// Ironworks and Weston Water Treatment, the settlement that asked from the event; DN151's 500 places something at
	// runtime), DLC03WorkshopRadiantOwned02 and 04, DLC04RaidCoerce (its 90 takes caps: StageRules) and
	// DLC04_RQ_KillRivalBoss, CollarRivalBoss, StealCache and DefendCache (whose attackers and defenders stand at markers:
	// what puts them there is to be read first). The others make NPCs at runtime (the robots' assaults and scenes, Far
	// Harbor's settlement attacks, the raids' raiders and defenders, the troublemakers), as the attacks RadiantRules
	// leaves alone.
	inline constexpr Local PER_GAME[] = {
		{ 0, 0x026340 },  // DN121: event SCPT; aliases 1 by conditions, 1 from the event, 2 made at runtime
		{ 0, 0x0482CD },  // DN151: event SCPT; aliases 1 by conditions, 1 from the event
		{ 1, 0x00EB4C },  // DLC03WorkshopRadiantOwned01: event SCPT; aliases 3 by conditions, 1 from the event, 1 made at runtime
		{ 1, 0x00EB51 },  // DLC03WorkshopRadiantOwned02: event SCPT; aliases 1 by conditions, 1 from the event
		{ 1, 0x039953 },  // DLC03WorkshopRadiantOwned03: event SCPT; aliases 2 by conditions, 1 from the event, 1 made at runtime
		{ 1, 0x040A86 },  // DLC03WorkshopRadiantOwned04: event SCPT; aliases 1 by conditions, 1 from the event
		{ 2, 0x003E8A },  // DLC01MQPostQuestRadiantAssault01: event SCPT; aliases 21 by conditions, 6 made at runtime
		{ 2, 0x003E8F },  // DLC01MQPostQuestRadiantScene01: event SCPT; aliases 14 by conditions, 2 made at runtime
		{ 2, 0x003E90 },  // DLC01MQPostQuestRadiantTravel01: event SCPT; aliases 8 by conditions, 1 made at runtime
		{ 2, 0x008508 },  // DLC01MQPostQuestRadiantTravel02: event SCPT; aliases 8 by conditions, 3 made at runtime
		{ 2, 0x00AF4C },  // DLC01MQPostQuestRadiantAssault04_Inst: event SCPT; aliases 21 by conditions, 6 made at runtime
		{ 2, 0x00AF4D },  // DLC01MQPostQuestRadiantAssault02: event SCPT; aliases 21 by conditions, 8 made at runtime
		{ 2, 0x00AF50 },  // DLC01MQPostQuestRadiantAssault03_Min: event SCPT; aliases 21 by conditions, 7 made at runtime
		{ 2, 0x00AF51 },  // DLC01MQPostQuestRadiantAssault05_BOS: event SCPT; aliases 22 by conditions, 12 made at runtime
		{ 2, 0x00D5FC },  // DLC01MQPostQuestRadiantScene02: event SCPT; aliases 15 by conditions, 2 made at runtime
		{ 3, 0x00DB37 },  // DLC04RaidWipeOut: event SCPT; aliases 1 by conditions, 2 from the event, 8 made at runtime
		{ 3, 0x014352 },  // DLC04RaidChaseOff: event SCPT; aliases 3 by conditions, 2 from the event, 3 made at runtime
		{ 3, 0x016E18 },  // DLC04RaidSubdue: event SCPT; aliases 2 by conditions, 2 from the event, 8 made at runtime
		{ 3, 0x017F46 },  // DLC04_RQ_KillRivalBoss: event SCPT; aliases 1 by conditions, 1 from the event
		{ 3, 0x019088 },  // DLC04RaidCoerce: event SCPT; aliases 3 by conditions, 2 from the event
		{ 3, 0x01B170 },  // DLC04_RQ_StealCache: event SCPT; aliases 21 by conditions, 1 from the event
		{ 3, 0x02191C },  // DLC04_RQ_DefendCache: event SCPT; aliases 21 by conditions, 1 from the event
		{ 3, 0x0322DA },  // DLC04_RQ_KillTroubleMaker: event SCPT; aliases 2 by conditions, 1 from the event, 2 made at runtime
		{ 3, 0x032A66 },  // DLC04_RQ_CollarTroubleMaker: event SCPT; aliases 2 by conditions, 1 from the event, 2 made at runtime
		{ 3, 0x04BD3C },  // DLC04_RQ_CollarRivalBoss: event SCPT; aliases 1 by conditions, 1 from the event
	};

	inline bool IsPerGame(std::uint8_t a_file, std::uint32_t a_quest)
	{
		return std::ranges::binary_search(PER_GAME, std::pair{ a_file, a_quest }, {}, [](const Local& a_local) { return std::pair{ a_local.file, a_local.quest }; });
	}

	// Quests whose progress is watched and shared: the shared types, the factions' finales and the
	// dialogue quests (the latter two with the story).
	inline bool Watched(const Quest& a_quest)
	{
		return IsSharedType(a_quest.type) || IsFinale(a_quest) || IsDialogue(a_quest);
	}
}
